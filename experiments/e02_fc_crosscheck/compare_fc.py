"""E02 - Cross-check our XMI reading against ShapeChange's Feature Catalogue (FC).

The FC (data/raw/approved/fc/FC_INSPIRE_v2025.1.tmp.xml) was generated by ShapeChange
from the INSPIRE EA model. Comparing it with our own reading of the XMI export shows
(a) whether our reader interprets the model like ShapeChange does and
(b) whether the FC and the XMI describe the same model state.

Compared per application schema / type / own property (no flattening on either side):
schema version, type category, abstract, supertypes, property name, cardinality,
voidable, value type name.

Usage:  python compare_fc.py  -> results/*.csv + summary on stdout
"""
from collections import Counter, defaultdict
from pathlib import Path
import csv
import re
import sys

from lxml import etree

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "e01_source_inventory"))
from xmi_load import load, NS, XMI_ID, XMI_IDREF, XMI_TYPE, ROOT  # noqa: E402
from inventory import stereotypes, tags  # noqa: E402

FC_PATH = ROOT / "data/raw/approved/fc/FC_INSPIRE_v2025.1.tmp.xml"
OUT = Path(__file__).parent / "results"

CATEGORY = {  # XMI first stereotype -> FC <type>
    "featuretype": "Spatial Object Type",
    "datatype": "Data Type",
    "union": "Union Data Type",
    "codelist": "Code List Type",
    "code list": "Code List Type",
    "enumeration": "Code List Type",
    "type": "Object Type",
}


def norm_mult(m):
    m = (m or "").strip()
    if m in ("", "1..1"):
        return "1"
    if m == "*":
        return "0..*"
    lo, _, hi = m.partition("..")
    return lo if hi == lo else m


# ---------------------------------------------------------------- FC side
def read_fc():
    root = etree.parse(str(FC_PATH)).getroot()
    byid = {e.get("id"): e for e in root if e.get("id")}
    schema_of_pkg = {}
    for e in root:
        if e.tag == "ApplicationSchema":
            schema_of_pkg[e.get("id")] = e.findtext("name")
    for _ in range(5):  # resolve nested Packages
        for e in root:
            if e.tag == "Package" and e.find("parent") is not None:
                p = e.find("parent").get("idref")
                if p in schema_of_pkg:
                    schema_of_pkg[e.get("id")] = schema_of_pkg[p]
    schemas = {e.findtext("name"): e.findtext("versionNumber") for e in root if e.tag == "ApplicationSchema"}
    types = {}
    for ft in root:
        if ft.tag != "FeatureType":
            continue
        schema = schema_of_pkg.get(ft.find("package").get("idref"), "?")
        props = {}
        for cb in ft.findall("characterizedBy"):
            p = byid.get(cb.get("idref"))
            if p is None:
                continue
            vt = p.find("ValueDataType")
            if vt is None:
                vt = p.find("FeatureTypeIncluded")
            props[p.findtext("name")] = dict(
                kind="role" if p.tag == "RelationshipRole" else "attr",
                mult=norm_mult(p.findtext("cardinality")),
                voidable=p.findtext("voidable") == "true",
                vtype=(vt.text or "").strip() if vt is not None else "",
            )
        values = []
        for eb in ft.findall("enumeratedBy"):  # not used by this FC version, kept for safety
            v = byid.get(eb.get("idref"))
            if v is not None:
                values.append(v.findtext("code"))
        types[(schema, ft.findtext("name"))] = dict(
            category=ft.findtext("type"),
            abstract=ft.findtext("isAbstract") in ("true", "1"),
            supers=sorted(byid[s.get("idref")].findtext("name") for s in ft.findall("subtypeOf")
                          if s.get("idref") in byid),
            props=props,
        )
    return schemas, types


# ---------------------------------------------------------------- XMI side
def read_xmi():
    root, _ = load()
    model = root.find(f"{{{NS['uml']}}}Model")
    ext = root.find(f"{{{NS['xmi']}}}Extension")
    ea = {e.get(XMI_IDREF): e for e in ext.find("elements")}
    byid = {e.get(XMI_ID): e for e in model.iter() if e.get(XMI_ID)}
    parent, pkg_name = {}, {}
    for p in model.iter("packagedElement"):
        if p.get(XMI_TYPE) == "uml:Package":
            pkg_name[p.get(XMI_ID)] = p.get("name")
            for c in p:
                if c.tag == "packagedElement":
                    parent[c.get(XMI_ID)] = p.get(XMI_ID)
    schemas, seen = {}, Counter()
    for pid, name in pkg_name.items():
        e = ea.get(pid)
        if e is not None and "applicationschema" in stereotypes(e):
            seen[name] += 1
            if seen[name] > 1:  # ShapeChange disambiguates duplicate package names the same way
                name = f"{name} ({seen[name]})"
            schemas[pid] = (name, tags(e).get("version", ""))

    def schema_of(eid):
        p = parent.get(eid)
        while p is not None and p not in schemas:
            p = parent.get(p)
        return schemas[p][0] if p else None

    def type_name(tref):
        if tref is None:
            return ""
        r = tref.get(XMI_IDREF) or ""
        if r in byid:
            return byid[r].get("name") or ""
        return r.split("_", 1)[1] if "_" in r else r

    types = {}
    cls_id_key = {}
    for c in model.iter("packagedElement"):
        if c.get(XMI_TYPE) not in ("uml:Class", "uml:AssociationClass", "uml:Enumeration", "uml:DataType"):
            continue
        e = ea.get(c.get(XMI_ID))
        if e is None or e.find("properties").get("sType") not in ("Class", "Enumeration", "DataType", None):
            continue
        sch = schema_of(c.get(XMI_ID))
        if sch is None:
            continue
        st = stereotypes(e)
        void_attrs, ea_attrs = set(), set()
        if e.find("attributes") is not None:
            void_attrs = {a.get("name") for a in e.find("attributes") if "voidable" in stereotypes(a)}
            ea_attrs = {a.get("name") for a in e.find("attributes")}
        props = {}
        for a in c.findall("ownedAttribute"):
            # some association ends are exported as ownedAttribute WITHOUT @association;
            # only properties listed in EA's own attribute list are real attributes
            if a.get("association") or not a.get("name") or a.get("name") not in ea_attrs:
                continue
            lo, hi = a.find("lowerValue"), a.find("upperValue")
            lo = lo.get("value") if lo is not None else "1"
            hi = hi.get("value") if hi is not None else "1"
            hi = "*" if hi in ("-1", "*") else hi
            props[a.get("name").strip()] = dict(kind="attr", mult=norm_mult(f"{lo}..{hi}"),
                                                voidable=a.get("name") in void_attrs, vtype=type_name(a.find("type")))
        for lit in c.findall("ownedLiteral"):
            props[(lit.get("name") or "").strip()] = dict(kind="attr", mult="1", voidable=False, vtype="")
        key = (sch, (c.get("name") or "").strip())
        types[key] = dict(
            category=next((CATEGORY[s] for s in st if s in CATEGORY), f"<{st[0]}>" if st else "<none>"),
            abstract=e.find("properties").get("isAbstract") == "true",
            supers=sorted(byid[g.get("general")].get("name") for g in c.findall("generalization")
                          if g.get("general") in byid),
            props=props,
        )
        cls_id_key[c.get(XMI_ID)] = key

    # association roles from EA connectors: an end's role becomes a property of the class at the other end
    nav_style = Counter()
    for cn in ext.find("connectors"):
        if cn.find("properties") is None or cn.find("properties").get("ea_type") not in ("Association", "Aggregation"):
            continue
        for end, other in (("source", "target"), ("target", "source")):
            e, o = cn.find(end), cn.find(other)
            role = e.find("role")
            if role is None or not role.get("name"):
                continue
            owner = cls_id_key.get(o.get(XMI_IDREF))
            if owner is None:
                continue
            style = (e.find("style").get("value") or "") if e.find("style") is not None else ""
            mod = e.find("modifiers").get("isNavigable") if e.find("modifiers") is not None else None
            # Navigability: EA style has Navigable / Unspecified / Non-Navigable; treating everything
            # except Non-Navigable as navigable agrees best with ShapeChange's FC (202/207 roles).
            # Alternatives tested and rejected (see README, E02): modifiers.isNavigable (almost always
            # "false"), UML ownedAttribute membership (199/207).
            navigable = "Navigable=Non-Navigable" not in style
            nav_style[(f"modifiers.isNavigable={mod}", f"style.Navigable={navigable}")] += 1
            if not navigable:  # not a property of the owner (FC agrees, see README)
                continue
            name = role.get("name").strip()
            if name in types[owner]["props"]:
                ROLE_CLASHES.append((*owner, name, types[owner]["props"][name]["vtype"], e.find("model").get("name")))
                continue
            types[owner]["props"][name] = dict(
                kind="role", mult=norm_mult(e.find("type").get("multiplicity") if e.find("type") is not None else ""),
                voidable="voidable" in stereotypes(e), vtype=e.find("model").get("name"))
    return {n: v for n, v in schemas.values()}, types, nav_style


ROLE_CLASHES = []  # (schema, class, property, kept type, dropped type)


def main():
    fc_schemas, fc = read_fc()
    xmi_schemas, xm, nav_style = read_xmi()
    OUT.mkdir(parents=True, exist_ok=True)
    summary = Counter()

    # schemas
    rows = []
    for s in sorted(set(fc_schemas) | set(xmi_schemas)):
        a, b = fc_schemas.get(s), xmi_schemas.get(s)
        status = "ONLY_XMI" if a is None else "ONLY_FC" if b is None else "OK" if a == b else "VERSION_DIFF"
        summary[f"schema:{status}"] += 1
        rows.append(dict(schema=s, fc_version=a or "", xmi_version=b or "", status=status))
    write(OUT / "schemas_fc_vs_xmi.csv", rows)

    # types and properties (only schemas present in both)
    common = set(fc_schemas) & set(xmi_schemas)
    trows, prows = [], []
    for key in sorted(set(k for k in fc if k[0] in common) | set(k for k in xm if k[0] in common)):
        a, b = fc.get(key), xm.get(key)
        if a is None or b is None:
            st = "ONLY_XMI" if a is None else "ONLY_FC"
            summary[f"type:{st}"] += 1
            trows.append(dict(schema=key[0], type=key[1], status=st,
                              xmi_category=b["category"] if b else "", fc_category=a["category"] if a else ""))
            continue
        diffs = [f for f in ("category", "abstract", "supers") if a[f] != b[f]]
        summary["type:" + ("OK" if not diffs else "DIFF")] += 1
        for f in diffs:
            summary[f"type.diff:{f}"] += 1
        trows.append(dict(schema=key[0], type=key[1], status="OK" if not diffs else "DIFF:" + "+".join(diffs),
                          xmi_category=b["category"], fc_category=a["category"],
                          xmi_abstract=b["abstract"], fc_abstract=a["abstract"],
                          xmi_supers="|".join(b["supers"]), fc_supers="|".join(a["supers"])))
        for p in sorted(set(a["props"]) | set(b["props"]), key=str):
            pa, pb = a["props"].get(p), b["props"].get(p)
            if pa is None or pb is None:
                st = "ONLY_XMI" if pa is None else "ONLY_FC"
                kind = (pb or pa)["kind"]
                if pa is None and pb.get("navigable") is False:
                    st += "(non-navigable)"
                summary[f"prop:{kind}:{st}"] += 1
                prows.append(dict(schema=key[0], type=key[1], prop=p, kind=kind, status=st,
                                  xmi_mult=pb["mult"] if pb else "", fc_mult=pa["mult"] if pa else "",
                                  xmi_voidable=pb["voidable"] if pb else "", fc_voidable=pa["voidable"] if pa else "",
                                  xmi_vtype=pb["vtype"] if pb else "", fc_vtype=pa["vtype"] if pa else ""))
                continue
            diffs = [f for f in ("mult", "voidable", "vtype") if pa[f] != pb[f]]
            summary[f"prop:{pa['kind']}:" + ("OK" if not diffs else "DIFF")] += 1
            for f in diffs:
                summary[f"prop.diff:{f}"] += 1
            prows.append(dict(schema=key[0], type=key[1], prop=p, kind=pa["kind"],
                              status="OK" if not diffs else "DIFF:" + "+".join(diffs),
                              xmi_mult=pb["mult"], fc_mult=pa["mult"], xmi_voidable=pb["voidable"],
                              fc_voidable=pa["voidable"], xmi_vtype=pb["vtype"], fc_vtype=pa["vtype"]))
    write(OUT / "types_fc_vs_xmi.csv", trows)
    write(OUT / "props_fc_vs_xmi.csv", prows)

    print("EA role ends by navigability flags:", dict(nav_style))
    print("property name clashes (schema, class, property, kept type, other type):", ROLE_CLASHES)
    for k in sorted(summary):
        print(f"  {k:40s} {summary[k]}")


def write(path, rows):
    keys = list(dict.fromkeys(k for r in rows for k in r))
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=keys)
        w.writeheader()
        w.writerows(rows)


if __name__ == "__main__":
    main()
